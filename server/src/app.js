import express from 'express';
import swaggerUi from 'swagger-ui-express';
import fs from 'node:fs';
import helmet from 'helmet';
import cors from 'cors';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {env} from './config/env.js';
import api,{uploads} from './routes/index.js';
import {optionalAuth} from './middleware/auth.js';
import {generalLimit} from './middleware/rateLimiter.js';
import {errorHandler} from './middleware/errorHandler.js';
import {notFound} from './middleware/notFound.js';
import ApiError from './utils/ApiError.js';
export const app=express();app.disable('x-powered-by');
// Render forwards requests through one trusted reverse-proxy hop.
if(process.env.RENDER==='true')app.set('trust proxy',1);
app.use(helmet({contentSecurityPolicy:{directives:{'img-src':["'self'",'data:','https:','http://localhost:5000'],'connect-src':["'self'",env.origin,'https://tile.openstreetmap.org']}}}));
app.use(cors({origin:env.nodeEnv==='production'?env.origin:[env.origin,'http://localhost:5173','http://127.0.0.1:5173']}));app.use(express.json({limit:'2mb'}));
app.use('/uploads',helmet({crossOriginResourcePolicy:{policy:'cross-origin'}}),express.static(uploads));
const contract=JSON.parse(fs.readFileSync(new URL('./openapi.json',import.meta.url),'utf8'));app.get('/api/openapi.json',(req,res)=>res.json(contract));app.use('/api/docs',swaggerUi.serve,swaggerUi.setup(contract));
app.use('/api',generalLimit,optionalAuth,api);app.use('/api',notFound);
const client=fileURLToPath(new URL('../../client/dist',import.meta.url));app.use(express.static(client));app.get('*',(req,res)=>res.sendFile(path.join(client,'index.html'),err=>{if(err)res.status(404).send('Frontend is not built yet. Run npm run build, or open http://localhost:5173 during development.');}));app.use(errorHandler);
export default app;
